import type { CareerRoadmapResult } from '../types/roadmap';

export function downloadRoadmapReport(roadmap: CareerRoadmapResult): void {
  const displayName = roadmap.studentName ? roadmap.studentName : 'Candidate';
  const generatedDate = new Date(roadmap.generatedAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const lines: string[] = [
    '========================================================================',
    'AI CAREER NAVIGATOR - SMART SKILL GAP ANALYZER',
    'Discover Your Skills. Identify Your Gaps. Build Your Future.',
    '========================================================================',
    '',
    `Prepared For:         ${displayName}`,
    `Target Career Role:   ${roadmap.targetRole}`,
    `Experience Level:     ${roadmap.experienceLevel}`,
    `Weekly Study Budget:  ${roadmap.hoursPerWeek} hours / week`,
    `Career Readiness:     ${roadmap.readinessPercentage}%`,
    `Generated Date:       ${generatedDate}`,
    '',
    'CAREER GOAL',
    '------------------------------------------------------------------------',
    roadmap.careerGoal,
    '',
    'READINESS ASSESSMENT',
    '------------------------------------------------------------------------',
    roadmap.readinessSummary,
    '',
    '1. EXISTING SKILLS',
    '------------------------------------------------------------------------',
    ...roadmap.existingSkills.flatMap((skill, i) => [
      `  ${i + 1}. ${skill.name}`,
      `     Relevance: ${skill.relevance}`,
      `     Next Step: ${skill.proficiencyNote}`,
    ]),
    '',
    '2. MISSING SKILLS (PRIORITY GAPS)',
    '------------------------------------------------------------------------',
    ...roadmap.missingSkills.flatMap((skill, i) => [
      `  ${i + 1}. [${skill.priority}] ${skill.name}`,
      `     Why It Matters: ${skill.reason}`,
    ]),
    '',
    '3. RECOMMENDED SKILLS TO LEARN',
    '------------------------------------------------------------------------',
    ...roadmap.recommendedSkills.flatMap((skill, i) => [
      `  ${i + 1}. ${skill.name} (${skill.category} - Est. ${skill.estimatedHours} hrs)`,
      `     Impact: ${skill.impact}`,
    ]),
    '',
    '4. PERSONALIZED 8-WEEK LEARNING ROADMAP',
    '------------------------------------------------------------------------',
    ...roadmap.weeklyRoadmap.flatMap((week) => [
      '',
      `  WEEK ${String(week.week).padStart(2, '0')}: ${week.title}`,
      `  Focus Area: ${week.focusArea} | Allocated Time: ${week.hoursAllocated} hrs`,
      `  Topics: ${week.topics.join(', ')}`,
      `  Milestone: ${week.milestone}`,
      `  Deliverable: ${week.deliverable}`,
    ]),
    '',
    '5. RECOMMENDED PRACTICAL PROJECTS (3)',
    '------------------------------------------------------------------------',
    ...roadmap.projects.flatMap((proj, i) => [
      '',
      `  PROJECT 0${i + 1}: ${proj.title}`,
      `  Difficulty: ${proj.difficulty} | Est. Effort: ${proj.estimatedHours} hrs`,
      `  Skills Applied: ${proj.skillsApplied.join(', ')}`,
      `  Description: ${proj.description}`,
      `  Portfolio Outcome: ${proj.outcome}`,
    ]),
    '',
    '6. CAREER IMPROVEMENT TIPS (5)',
    '------------------------------------------------------------------------',
    ...roadmap.careerTips.flatMap((tip, i) => [
      '',
      `  0${i + 1}. ${tip.title} (${tip.category})`,
      `      Actionable Step: ${tip.actionableStep}`,
    ]),
    '',
    '========================================================================',
    'Generated by AI Career Navigator - Smart Skill Gap Analyzer',
    '========================================================================',
  ];

  const content = lines.join('\n');
  const safeRole = roadmap.targetRole.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const filename = `career-roadmap-${safeRole || 'plan'}.txt`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
